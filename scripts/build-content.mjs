// Build-time script: reads MDX frontmatter and generates a static module.
// This avoids filesystem reads at request time on Cloudflare Workers.
import fs from 'fs';
import path from 'path';
import matter from 'gray-matter';

const blogDir = path.join(process.cwd(), 'src', 'content', 'blog');
const outFile = path.join(process.cwd(), 'src', 'lib', 'generated-posts.ts');

const files = fs.readdirSync(blogDir).filter(f => path.extname(f) === '.mdx');

const posts = files.map(file => {
  const filePath = path.join(blogDir, file);
  const rawContent = fs.readFileSync(filePath, 'utf-8');
  const { data, content } = matter(rawContent);
  const slug = path.basename(file, path.extname(file));
  
  return {
    slug,
    metadata: data,
    rawContent: content,
  };
});

// Sort by date descending
posts.sort((a, b) => new Date(b.metadata.date) - new Date(a.metadata.date));

const output = `// Auto-generated by scripts/build-content.mjs - do not edit manually
export const generatedPosts = ${JSON.stringify(posts, null, 2)};
`;

fs.writeFileSync(outFile, output);
console.log(`Generated ${outFile} with ${posts.length} posts`);
